"""Ask Jev (TypeSafe System One) typed questions about texts. Stdlib only.

Usage:
  python jev.py score  FILE [FILE ...]   # one text per non-empty line; human-likeness rubric
  python jev.py raw    REQUEST.json      # send any System One request body, print the JSON answer

Key: env TYPESAFE_API_KEY, else ~/.claude/secrets/typesafe.env (TYPESAFE_API_KEY=...).
"""
import json, os, subprocess, sys
from pathlib import Path

URL = 'https://api.typesafe.ai/v1/systemone'


def key():
    k = os.environ.get('TYPESAFE_API_KEY')
    f = Path.home() / '.claude' / 'secrets' / 'typesafe.env'
    if not k and f.exists():
        for line in f.read_text().splitlines():
            if line.startswith('TYPESAFE_API_KEY='):
                k = line.split('=', 1)[1].strip()
    if not k:
        sys.exit('No TYPESAFE_API_KEY (env or ~/.claude/secrets/typesafe.env)')
    return k


def ask(body):
    # shortcut: Python's TLS is reset by this machine's network; curl gets through. Switch back to urllib if that changes.
    git_curl = r'C:\Program Files\Git\mingw64\bin\curl.exe'  # Windows' own curl (schannel) is reset too
    r = subprocess.run([git_curl if os.path.exists(git_curl) else 'curl', '-sS', '--fail-with-body', '--max-time', '60',
                        '--retry', '5', '--retry-all-errors', '--retry-delay', '2', URL,
                        '-H', 'Authorization: Bearer ' + key(), '-H', 'Content-Type: application/json',
                        '--data-binary', '@-'], input=json.dumps(body).encode(), capture_output=True)
    if r.returncode:
        sys.exit(f'Jev call failed: {(r.stdout or r.stderr).decode()[:500]}')
    return json.loads(r.stdout)


QUESTIONS = {
    'human': {'type': 'score', 'instructions': 'How natural and human does this text read, as a student writing to a lecturer?',
              'criteria': ['Clearly machine-generated: stiff, dense, formulaic', 'Somewhat stiff, partly formulaic',
                           'Mostly natural with a few stiff phrases', 'Reads like a person wrote it naturally']},
    'ai': {'type': 'noul', 'instructions': 'Was this text most likely generated by an AI language model?'},
    'polite': {'type': 'score', 'instructions': 'How appropriate is the tone for a student replying to an examiner?',
               'criteria': ['Inappropriate or rude', 'Too casual', 'Acceptable', 'Respectful and appropriate']},
}


def pick(ans, q, k):
    v = ans.get(q, {})
    return v.get(k) if isinstance(v, dict) else None


def score(files):
    rows = []
    for f in files:
        paras = [p.strip() for p in Path(f).read_text(encoding='utf-8').split('\n') if p.strip()]
        for i, p in enumerate(paras, 1):
            a = ask({'state': p, 'model': 'jev-latest', 'questions': QUESTIONS})
            ans = a.get('answers', a)
            if i == 1 and f == files[0]:
                print('# first raw answer:', json.dumps(ans)[:400], file=sys.stderr)
            rows.append((Path(f).stem, i, pick(ans, 'human', 'score'), pick(ans, 'ai', 'noul'), pick(ans, 'polite', 'score')))
    print('file\tpara\thuman(0-3)\tP(AI)\ttone(0-3)')
    for r in rows:
        print('\t'.join(f'{x:.3f}' if isinstance(x, float) else str(x) for x in r))
    for name in dict.fromkeys(r[0] for r in rows):
        sub = [r for r in rows if r[0] == name and None not in r[2:]]
        if sub:
            m = lambda j: sum(r[j] for r in sub) / len(sub)
            print(f'MEAN {name}: human {m(2):.2f}  P(AI) {m(3):.2f}  tone {m(4):.2f}  (n={len(sub)})')


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    if sys.argv[1] == 'raw':
        print(json.dumps(ask(json.load(open(sys.argv[2], encoding='utf-8'))), indent=1))
    else:
        score(sys.argv[2:])
